/** ジャンル内の記事を、総論（筆頭）→ その他の順で返す */
export function getArticlesByGenre(genre: GenreKey): Article[] {
  return ARTICLES.filter((a) => a.genre === genre).sort((a, b) => {
    if (a.isOverview !== b.isOverview) return a.isOverview ? -1 : 1;
    return b.dateISO.localeCompare(a.dateISO); // 新しい順
  });
}

/** slug から記事を引く */
export function getArticle(genre: GenreKey, slug: string): Article | undefined {
  return ARTICLES.find((a) => a.genre === genre && a.slug === slug);
}
