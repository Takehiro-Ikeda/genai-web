/**
 * コラム記事データ（全ジャンル共通の一元管理）
 *
 * 設計方針：
 * - URL（slug）と分類（genre / isOverview）を分離して保持する。
 *   例：A-1総論は slug="visibility" だが、genre="security" / isOverview=true で「Aジャンルの筆頭総論」と判別できる。
 * - 記事が増えても、順番が変わっても、番号スラッグのように破綻しない。
 * - B/C/D の総論も同じ構造で並べられる（全ジャンル共通）。
 *
 * 本文（body）について：
 * - 段落・見出し・強調を構造化データで保持し、記事詳細ページ側で prose-column 組版にレンダリングする。
 * - block種別： 'p'（段落）/ 'h'（見出し）。inline配列内の { strong: true } で teal 強調。
 */

export type GenreKey = 'security' | 'business' | 'healthcare' | 'tacit-knowledge';

export type InlineNode =
  | string
  | { text: string; strong?: boolean };

export type ArticleBlock =
  | { type: 'h'; text: string }
  | { type: 'p'; nodes: InlineNode[] };

export type Article = {
  slug: string; // ジャンル内で一意（URL: /column/{genre}/{slug}）
  genre: GenreKey;
  isOverview: boolean; // 総論（筆頭）か
  title: string;
  subtitle?: string;
  lead: string; // 一覧カードに出す要約（1〜2文）
  author: string;
  date: string; // 表示用（例：2026.06.01）
  dateISO: string; // 機械可読（例：2026-06-01）
  body: ArticleBlock[];
};

export type Genre = {
  key: GenreKey;
  badge: string; // 例：A
  label: string; // 例：セキュリティ × 生成AI
  title: string; // 例：セキュリティ
  lead: string; // ジャンルの問い
  comingSoon: boolean; // 記事がまだ無いジャンルは true
};

